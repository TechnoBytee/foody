for (const file of files) {
  const filePath = path.join(dir, file);
  let content = fs.readFileSync(filePath, "utf8");

  content = content.replace(
    /"name":\s*\{\s*"tr":\s*"([^"]+)",\s*"en":\s*"([^"]+)"\s*\}/g,
    (_, tr, en) => {
      const trName = translateName(tr);
      return `"name": { "tr": "${trName}", "en": "${en}" }`;
    }
  );

  content = content.replace(
    /"ingredients":\s*\[([\s\S]*?)\]/g,
    (_, ingredientsStr) => {
      const ingredients = ingredientsStr.match(/"([^"]+)"/g) || [];
      const translated = ingredients.map((ing) => {
        const clean = ing.slice(1, -1);
        return `"${translateIngredient(clean)}"`;
      });
      return `"ingredients": [${translated.join(", ")}]`;
    }
  );

  content = content.replace(
    /"steps":\s*\{\s*"tr":\s*\[([\s\S]*?)\],\s*"en":\s*\[([\s\S]*?)\]\s*\}/g,
    (_, trStepsStr, enStepsStr) => {
      const trSteps = trStepsStr.match(/"([^"]+)"/g) || [];
      const enSteps = enStepsStr.match(/"([^"]+)"/g) || [];
      const translatedTr = trSteps.map((s) => {
        const clean = s.slice(1, -1);
        return `"${translateStep(clean)}"`;
      });
      const translatedEn = enSteps.map((s) => {
        const clean = s.slice(1, -1);
        return `"${clean}"`;
      });
      return `"steps": { "tr": [${translatedTr.join(", ")}], "en": [${translatedEn.join(", ")}] }`;
    }
  );

  fs.writeFileSync(filePath, content);
  console.log("Translated:", file);
}
