function translateIngredient(ing) {
  const lower = ing.toLowerCase();
  for (const [en, tr] of Object.entries(ingredientDict)) {
    if (lower.includes(en)) {
      return lower.replace(new RegExp(en, "gi"), tr);
    }
  }
  return ing;
}

function translateStep(step) {
  for (const [pattern, replacer] of stepPatterns) {
    const m = step.match(pattern);
    if (m) {
      return replacer(m, ...m.slice(1));
    }
  }
  return step;
}

function translateName(name) {
  const lower = name.toLowerCase();
  for (const [en, tr] of Object.entries(ingredientDict)) {
    if (lower.includes(en)) {
      return lower.replace(new RegExp(en, "gi"), tr);
    }
  }
  return name;
}

